// Renders manifest.gen.ts from the full page registry (docs/prd.md § v3.F).
//
// Node-only: vite.config.ts calls writeSmellManifest() at config time, and
// src/__tests__/smells.test.ts checks the committed file is current. Client
// code never imports this module or index.ts's SMELL_PAGES; it reads
// manifest.gen.ts (metadata) and load.ts (one page's content, on demand).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { SMELL_PAGES } from "./index";
import type { SmellMeta } from "./types";

const DIR = fileURLToPath(new URL(".", import.meta.url));
const OUT = `${DIR}manifest.gen.ts`;

/** path → page file stem, read from each file's top-level `path:` line. */
function pageFiles(): Record<string, string> {
  const files: Record<string, string> = {};
  for (const f of readdirSync(`${DIR}pages`)
    .filter((n) => n.endsWith(".ts"))
    .sort()) {
    const m = readFileSync(`${DIR}pages/${f}`, "utf8").match(/^ {2}path: "([^"]+)"/m);
    if (m) files[m[1]] = f.slice(0, -3);
  }
  return files;
}

export function renderSmellManifest(): string {
  const files = pageFiles();
  const meta: SmellMeta[] = SMELL_PAGES.map((p) => ({
    path: p.path,
    family: p.family,
    title: p.title,
    description: p.description,
    h1: p.h1,
    label: p.label,
    urgency: p.urgency,
    diagnose: p.diagnose,
    updated: p.updated,
  }));
  const fileMap = Object.fromEntries(
    SMELL_PAGES.map((p) => {
      const f = files[p.path];
      if (!f) throw new Error(`smell manifest: no file in pages/ declares path ${p.path}`);
      return [p.path, f];
    }),
  );
  return [
    "// GENERATED by src/content/smells/manifest-build.ts (run by vite.config.ts).",
    "// Do not edit — change the page file in pages/ or SMELL_PAGES in index.ts.",
    'import type { SmellMeta } from "./types";',
    "",
    "/** Registry order (= hub order). */",
    `export const SMELL_META: SmellMeta[] = ${JSON.stringify(meta, null, 2)};`,
    "",
    "/** Canonical path → page file stem in pages/. */",
    `export const SMELL_FILES: Record<string, string> = ${JSON.stringify(fileMap, null, 2)};`,
    "",
  ].join("\n");
}

/** Rewrites manifest.gen.ts only when it changed (keeps dev HMR quiet). */
export function writeSmellManifest(): void {
  const next = renderSmellManifest();
  let prev = "";
  try {
    prev = readFileSync(OUT, "utf8");
  } catch {
    /* first run */
  }
  if (prev !== next) writeFileSync(OUT, next);
}

export const SMELL_MANIFEST_PATH = OUT;
